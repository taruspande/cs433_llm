"""
Magicoder OSS-Instruct, Python subset: ~38K programming problems with solutions (generated by GPT-3.5 from
open-source code snippets, MIT license).
https://huggingface.co/datasets/ise-uiuc/Magicoder-OSS-Instruct-75K

!!! DO NOT MODIFY THIS FILE: it is part of the dataset catalog (see scripts/prepare_data.py). !!!
"""

from tasks.common import Task, load_hub_dataset

class Magicoder(Task):

    def __init__(self, **kwargs):
        super().__init__(**kwargs)
        ds = load_hub_dataset("ise-uiuc/Magicoder-OSS-Instruct-75K", split="train")
        self.rows = [r for r in (ds[i] for i in range(len(ds))) if r["lang"] == "python"]

    @property
    def eval_type(self):
        return 'generative'

    def num_examples(self):
        return len(self.rows)

    def get_example(self, index):
        row = self.rows[index]
        messages = [
            {"role": "user", "content": row["problem"].strip()},
            {"role": "assistant", "content": row["solution"].strip()},
        ]
        return {"messages": messages}
