"""
TinyGSM: 11.8M synthetic grade-school math problems with Python solutions (generated by GPT-3.5).
https://huggingface.co/datasets/TinyGSM/TinyGSM

Rendered in the format of the `python_math` evaluation subset: the user asks for a function
`solution()` that returns the answer, the assistant answers with a Python code block.
Only the first parquet shard (~700K problems) is downloaded, which is plenty for SFT.

!!! DO NOT MODIFY THIS FILE: it is part of the dataset catalog (see scripts/prepare_data.py). !!!
"""

import os
import json

import pyarrow.parquet as pq
from filelock import FileLock

from nanochat.common import get_base_dir, hf_request
from tasks.common import Task
from tasks.eval_suite import render_python_math_question


def _first_shard_path():
    shard_dir = os.path.join(get_base_dir(), "task_data", "TinyGSM--TinyGSM")
    path = os.path.join(shard_dir, "00000.parquet")
    if not os.path.exists(path):
        os.makedirs(shard_dir, exist_ok=True)
        with FileLock(path + ".lock"):
            if not os.path.exists(path):
                urls = json.loads(hf_request("https://huggingface.co/api/datasets/TinyGSM/TinyGSM/parquet/default/train"))
                print(f"Downloading {urls[0]} ...")
                content = hf_request(urls[0])
                with open(path + ".tmp", "wb") as f:
                    f.write(content)
                os.rename(path + ".tmp", path)
    return path


class TinyGSM(Task):

    def __init__(self, **kwargs):
        super().__init__(**kwargs)
        self.table = pq.read_table(_first_shard_path(), columns=["question", "code"])

    @property
    def eval_type(self):
        return 'generative'

    def num_examples(self):
        return self.table.num_rows

    def get_example(self, index):
        question = self.table["question"][index].as_py()
        code = self.table["code"][index].as_py().replace("simple_math_problem", "solution").strip()
        messages = [
            {"role": "user", "content": render_python_math_question(question)},
            {"role": "assistant", "content": f"```python\n{code}\n```"},
        ]
        return {"messages": messages}
